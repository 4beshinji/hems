# ---------------------------------------------------------------------------
# Fixture: paho mqtt client factory
# ---------------------------------------------------------------------------


@pytest.fixture
def mqtt_client_factory():
    """Return a factory that creates authenticated paho MQTT clients.

    Each returned client connects synchronously and is disconnected on teardown.
    The fixture itself just imports paho — the ``_skip_if_no_broker`` call must
    happen inside individual tests so the skip reason is accurate.
    """
    paho = pytest.importorskip("paho.mqtt.client", reason="paho-mqtt not installed")

    clients = []

    def _make(username: str, password: str):
        client = paho.Client(client_id=f"test-{username}-{uuid.uuid4().hex[:8]}")
        client.username_pw_set(username, password)
        clients.append(client)
        return client

    yield _make

    for c in clients:
        try:
            c.disconnect()
        except Exception:
            pass


# ---------------------------------------------------------------------------
# Core helper: attempt publish and check broker ACL response
# ---------------------------------------------------------------------------


def _publish_and_check_rc(
    client_factory,
    username: str,
    password: str,
    topic: str,
) -> int | None:
    """Connect as *username*, attempt to publish to *topic*, return the rc.

    Mosquitto with ACL enforced returns rc=1 (connection refused) when auth
    fails, or rc=0 but the message is silently dropped / PUBACK withheld when
    ACL denies a publish.

    Returns None when the broker is unreachable (causes test skip).
    """
    import paho.mqtt.client as paho

    received_rc = []
    connected = []

    def on_connect(client, userdata, flags, rc, properties=None):
        connected.append(rc)

    def on_publish(client, userdata, mid):
        # only fires on successful broker ACK
        received_rc.append(0)

    client = paho.Client(client_id=f"test-{username[:12]}-{uuid.uuid4().hex[:6]}")
    client.username_pw_set(username, password)
    client.on_connect = on_connect
    client.on_publish = on_publish

    try:
        client.connect(MQTT_HOST, MQTT_PORT, keepalive=5)
    except OSError:
        return None  # broker unreachable

    client.loop_start()
    deadline = time.monotonic() + _TIMEOUT
    while not connected and time.monotonic() < deadline:
        time.sleep(0.05)
    client.loop_stop()

    if not connected:
        return None  # timed out

    conn_rc = connected[0]

    if conn_rc != 0:
        # Authentication itself failed (bad password, not ACL)
        try:
            client.disconnect()
        except Exception:
            pass
        return conn_rc

    # Connected — attempt publish, wait briefly for PUBACK
    client.loop_start()
    msg_info = client.publish(topic, payload="acl-test", qos=1, retain=False)
    deadline = time.monotonic() + _TIMEOUT
    while not msg_info.is_published() and time.monotonic() < deadline:
        time.sleep(0.05)
    client.loop_stop()

    try:
        client.disconnect()
    except Exception:
        pass

    # is_published() True means broker acknowledged the publish.
    # ACL-denied publishes either: never get PUBACK (QoS 1) or
    # Mosquitto ≥ 2.0 sends a DISCONNECT with reason code 135 (Not authorized).
    return 0 if msg_info.is_published() else 135  # 135 = MQTT Not Authorized


# ---------------------------------------------------------------------------
# Parametrised test
# ---------------------------------------------------------------------------


@pytest.mark.integration
@pytest.mark.parametrize("username,topic,operation", _ACL_DENY_SCENARIOS)
def test_mqtt_acl_rejects_forbidden_publish(username, topic, operation, mqtt_client_factory):
    """Service user must NOT be able to publish to a forbidden topic.

    The test skips if:
    - The broker is unreachable (CI without Docker).
    - paho-mqtt is not installed.
    - The password for the user is not configured (unknown in test env).
    """
    _skip_if_no_broker()

    if operation != "publish":
        pytest.skip(f"Subscribe ACL test not implemented yet (scenario: {username}/{topic})")

    password = _DEFAULT_PASSWORDS.get(username)
    if not password:
        pytest.skip(f"No password configured for {username}")

    rc = _publish_and_check_rc(mqtt_client_factory, username, password, topic)

    if rc is None:
        pytest.skip(f"Broker unreachable or timed out while testing {username} → {topic}")

    # rc == 0 and PUBACK received means the broker accepted the publish — FAIL
    # rc != 0 or no PUBACK means the broker rejected it — PASS
    assert rc != 0, (
        f"Broker accepted forbidden publish: user={username!r} topic={topic!r} "
        f"(rc={rc}). Check infra/mosquitto/aclfile — the ACL may be missing or "
        f"the broker may be running without ACL enforcement."
    )
