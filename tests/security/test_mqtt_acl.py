# Broker connection parameters (override via env vars)
# ---------------------------------------------------------------------------

MQTT_HOST = os.getenv("MQTT_HOST", "127.0.0.1")
MQTT_PORT = int(os.getenv("MQTT_PORT", "1893"))
_TIMEOUT = 5  # seconds


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _broker_reachable() -> bool:
    """Return True when a TCP connection to the broker can be established."""
    try:
        with socket.create_connection((MQTT_HOST, MQTT_PORT), timeout=3):
            return True
    except OSError:
        return False


def _skip_if_no_broker():
    """pytest.skip the calling test when the broker is not available."""
    if not _broker_reachable():
        pytest.skip(f"MQTT broker not reachable at {MQTT_HOST}:{MQTT_PORT}")


