"""
W1.7 — MQTT ACL rejection tests.

Each service user is allowed to publish/subscribe only to a restricted topic
set (see infra/mosquitto/aclfile).  These tests verify that a service user
*cannot* publish to a topic outside its ACL — i.e. that the broker actively
rejects unauthorised publishes.

Marker: ``@pytest.mark.integration``
Requires a live Mosquitto broker configured with the project aclfile and
passwords file.  When the broker is unreachable the test is automatically
skipped — it is safe to run in a "no-broker" CI environment.

Run integration tests:
    PYTHONPATH=services/brain/src:services/backend \\
      pytest tests/security/test_mqtt_acl.py -m integration -v

Run in-CI (skip integration):
    pytest tests/security/ -m "not integration" -v
"""

